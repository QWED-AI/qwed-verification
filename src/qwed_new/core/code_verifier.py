    @staticmethod
    def _positions(haystack: str, needles: tuple) -> List[int]:
        """Sorted start indices of any needle in haystack (one pass per needle)."""
        found: List[int] = []
        for needle in needles:
            start = 0
            while True:
                i = haystack.find(needle, start)
                if i == -1:
                    break
                found.append(i)
                start = i + 1
        found.sort()
        return found

    def _check_remote_pipe_to_shell(self, code: str) -> List[SecurityIssue]:
        """Flag `subprocess.*` calls that pipe curl/wget output into a shell.

        Replaces the old chained-`.*?` regex. The token positions are collected
        once, up front; each subprocess match then uses a binary search to check
        that a fetch tool, a shell separator and a shell appear after it, in
        order. Overall O(n + matches·log n) — no rescan per match, no
        backtracking. One finding per line.
        """
        issues: List[SecurityIssue] = []
        # All positions are computed against `code` (case-insensitive regexes),
        # so offsets never drift the way `code.lower()` can for characters whose
        # lowercase form changes length (Sentry on PR #447).
        fetch_pos = [m.start() for m in self._FETCH_TOOL.finditer(code)]
        if not fetch_pos:
            return issues
        sep_pos = self._positions(code, ("|", ";", "&&"))
        if not sep_pos:
            return issues
        shell_pos = [m.start() for m in self._SHELL_TARGET.finditer(code)]
        if not shell_pos:
            return issues
        # Everything else is precomputed too, so each match is O(log n) and the
        # worst case (many matches on one line) stays near-linear overall.
        newline_pos = self._positions(code, ("\n",))
        shell_true_pos = [m.start() for m in self._SHELL_TRUE.finditer(code)]
        seen_lines = set()
        for match in self._SUBPROC_CALL.finditer(code):
            fi = bisect_left(fetch_pos, match.end())
            if fi == len(fetch_pos):
                continue
            si = bisect_left(sep_pos, fetch_pos[fi])
            if si == len(sep_pos):
                continue
            hi = bisect_left(shell_pos, sep_pos[si])
            if hi == len(shell_pos):
                continue
            line_num = bisect_left(newline_pos, match.start()) + 1
            if line_num in seen_lines:
                continue
            seen_lines.add(line_num)
            ti = bisect_left(shell_true_pos, match.start())
            if ti != len(shell_true_pos):
                description = "Remote code execution via shell=True with curl/wget pipe to shell."
                recommendation = "Never execute remote pipe commands with shell=True."
            else:
                description = "Suspicious curl/wget pipe-to-shell pattern detected (heuristic)."
                recommendation = "Never pipe remote content directly into a shell."
            issues.append(SecurityIssue(
                severity="CRITICAL",
                issue_type="remote_code_execution",
                pattern="subprocess + curl|wget pipe to shell",
                description=description,
                line_number=line_num,
                recommendation=recommendation,
            ))
        return issues

    def _check_python(self, code: str) -> List[SecurityIssue]:
        """Check Python code for security issues."""
        # The AST checks share one parse and one walk of it; code that does
        # not parse stops here.
        nodes = list(ast.walk(self._parse_python(code)))
        issues = []
        lines = code.split('\n')
        
        for line_num, line in enumerate(lines, 1):
            # Critical functions; the builtins among them are matched as
            # names in _check_python_critical_builtins (#534).
            for pattern, desc in self.PYTHON_CRITICAL.items():
                if pattern not in self.PYTHON_CRITICAL_BUILTINS and pattern in line:
                    issues.append(SecurityIssue(
                        severity="CRITICAL",
                        issue_type="dangerous_function",
                        pattern=pattern,
                        description=desc,
                        line_number=line_num,
                        recommendation="Remove or sandbox this operation"
                    ))
            
            # Shell and process execution: one blocking finding per line.
            for prefix in self.PYTHON_PROCESS_EXECUTION:
                if prefix in line:
                    issues.append(self._process_execution_issue(prefix.rstrip("._"), line_num))
                    break

            # File / network access: one blocking finding per line (GHSA-4phf).
            for prefix in self.PYTHON_FILE_NETWORK:
                if prefix in line:
                    issues.append(self._file_network_issue(prefix.rstrip("."), line_num))
                    break

            # Warning functions
            for pattern, desc in self.PYTHON_WARNING.items():
                if pattern in line:
                    issues.append(SecurityIssue(
                        severity="WARNING",
                        issue_type="context_dependent",
                        pattern=pattern,
                        description=desc,
                        line_number=line_num,
                        recommendation="Verify input source is trusted"
                    ))
            
            # Dangerous attributes
            for attr in self.PYTHON_DANGEROUS_ATTRS:
                if attr in line:
                    issues.append(SecurityIssue(
                        severity="CRITICAL",
                        issue_type="dangerous_attribute",
                        pattern=attr,
                        description=f"Dangerous attribute access: {attr}",
                        line_number=line_num
                    ))

        issues.extend(self._check_python_critical_builtins(nodes))

        # A subprocess call that pipes curl/wget output into a shell, including
        # across lines. Linear scan (no backtracking regex) over the full code.
        for issue in self._check_remote_pipe_to_shell(code):
            if any(
                i.issue_type == issue.issue_type and i.line_number == issue.line_number
                for i in issues
            ):
                continue
            issues.append(issue)

        # Process execution reached through an alias, which the line scan cannot see.
        for issue in self._check_python_process_ast(nodes):
            if any(
                i.issue_type == issue.issue_type
                and i.line_number == issue.line_number
                for i in issues
            ):
                continue
            issues.append(issue)

        # AST-based subprocess checks to catch nested expression forms that regex can miss.
        for issue in self._check_python_subprocess_ast(nodes):
            if any(
                i.issue_type == issue.issue_type
                and i.line_number == issue.line_number
                for i in issues
            ):
                continue
            issues.append(issue)
        
        # Weak crypto in password context
        code_lower = code.lower()
        has_password = any(p in code_lower for p in self.PASSWORD_INDICATORS)
        if has_password:
            for pattern, desc in self.PYTHON_WEAK_CRYPTO.items():
                if pattern in code:
                    issues.append(SecurityIssue(
                        severity="CRITICAL",
                        issue_type="weak_crypto_with_password",
                        pattern=pattern,
                        description=f"{desc} - used in password context",
                        recommendation="Use bcrypt, argon2, or scrypt for passwords"
                    ))
        
        return issues

    @staticmethod
    def _parse_python(code: str) -> ast.AST:
        """The module's AST. Code that does not parse raises
        _UnparseablePython, which verify_code turns into BLOCKED: the AST
        checks cannot run on it, so it is not certified."""
        try:
            return ast.parse(code)
        except (SyntaxError, ValueError) as exc:  # ValueError: null bytes on Python 3.10
            raise _UnparseablePython() from exc

    def _process_execution_issue(self, pattern: str, line_number: Optional[int]) -> SecurityIssue:
        return SecurityIssue(
            severity="CRITICAL",
            issue_type="process_execution",
            pattern=pattern,
            description="Shell or process execution",
            line_number=line_number,
            recommendation="Do not run commands from generated code; route them through a reviewed, sandboxed tool.",
        )

    def _is_process_execution(self, name: str) -> bool:
        return any(name.startswith(prefix) for prefix in self.PYTHON_PROCESS_EXECUTION)

    def _file_network_issue(self, pattern: str, line_number: Optional[int]) -> SecurityIssue:
        return SecurityIssue(
            severity="CRITICAL",
            issue_type="file_or_network_access",
            pattern=pattern,
            description="File system or network access",
            line_number=line_number,
            recommendation="Generated code must not read/write files or perform network I/O; route any I/O through a reviewed, sandboxed tool.",
        )

    def _is_file_network(self, name: str) -> bool:
        return any(name.startswith(prefix) for prefix in self.PYTHON_FILE_NETWORK)

    @staticmethod
    def _dotted_name(node: ast.AST) -> Optional[str]:
        """``a.b.c`` for a Name/Attribute chain, else None."""
        parts: List[str] = []
        while isinstance(node, ast.Attribute):
            parts.append(node.attr)
            node = node.value
        if not isinstance(node, ast.Name):
            return None
        parts.append(node.id)
        return ".".join(reversed(parts))

    @staticmethod
    def _import_aliases(nodes: List[ast.AST]) -> tuple[Dict[str, str], List[str]]:
        """Names bound by imports, mapped to the dotted name they stand for,
        and the modules star-imported."""
        aliases: Dict[str, str] = {}
        star_modules: List[str] = []
        for node in nodes:
            if isinstance(node, ast.Import):
                aliases.update(CodeVerifier._import_binding(alias) for alias in node.names)
            elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
                star_modules.extend(node.module for alias in node.names if alias.name == "*")
                aliases.update(
                    (alias.asname or alias.name, f"{node.module}.{alias.name}")
                    for alias in node.names if alias.name != "*"
                )
        return aliases, star_modules

    @staticmethod
    def _import_binding(alias: ast.alias) -> tuple[str, str]:
        """The name ``import <alias>`` binds, and the module it binds it to."""
        if alias.asname:
            return alias.asname, alias.name
        top = alias.name.split(".")[0]
        return top, top

    def _check_python_critical_builtins(self, nodes: List[ast.AST]) -> List[SecurityIssue]:
        """Flag the critical builtins as names, not substrings (#534).

        On the AST:
        - a Name that is the builtin, called or not (``f = eval``), whatever an
          import elsewhere binds to it: imports are not scoped or ordered here,
          so ``exec(x)`` stays refused beside ``from re import compile as exec``;
        - an import from the builtins module (``import builtins as b``);
        - an attribute read with the builtin's name, or one of the dunder
          accessors (``__getattribute__``), since the object may be the
          builtins module reached another way: ``m.exec``, ``from m import
          exec as run`` and the match pattern ``case object(exec=run)``. The
          one exception is ``re.compile`` called as ``re.compile(pattern,
          flags)`` on a name every import binds to ``re`` and nothing
          rebinds (_untrusted_compiles);
        - a string holding one of these names as a whole identifier, since
          ``vars(module)["exec"]`` reaches it by string, or a name that
          slicing, %-formatting or stripping a literal can leave, the literal
          written in place or reaching the step another way (``"xexec"[1:]``,
          ``s = "xexec"; s[1:]``, ``ident("xexec")[1:]``;
          _reshaped_references).
        Comments, longer identifiers such as ``execute``, ``evaluate`` and
        ``compile_report``, prose in strings, and a class or module defining
        ``__getattr__`` are not matches.
        """
        found: List[tuple[str, int]] = []
        compile_attributes: List[ast.Attribute] = []
        reshapes: List[ast.AST] = []
        for node in nodes:
            node_type = type(node)
            if node_type in self._RESHAPE_NODE_TYPES:
                reshapes.append(node)
            if node_type not in self._REFERENCE_NODE_TYPES:
                continue
            name = self._critical_builtin_reference(node)
            if name == "compile" and isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
                compile_attributes.append(node)
            elif name:
                found.append((name, node.lineno))
        # Only code with a name.compile pays for the walk that finds re.
        if compile_attributes:
            found.extend(("compile", node.lineno) for node in self._untrusted_compiles(nodes, compile_attributes))
        if reshapes:
            found.extend(self._reshaped_references(nodes, reshapes))
        unique = list(dict.fromkeys(found))  # (name, line) pairs, in order, once each
        return [self._critical_builtin_issue(name, line) for name, line in unique]

    def _critical_builtin_reference(self, node: ast.AST) -> Optional[str]:
        """The critical builtin (or builtins module) ``node`` refers to."""
        if isinstance(node, ast.Name):
            return node.id if node.id in self._CRITICAL_NAMES else None
        if isinstance(node, ast.Attribute) and node.attr in self._ATTRIBUTE_READ_NAMES:
            return node.attr
        if isinstance(node, ast.MatchClass):
            return next((attr for attr in node.kwd_attrs if attr in self._ATTRIBUTE_READ_NAMES), None)
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            return self._import_reference(node)
        if isinstance(node, ast.Constant) and isinstance(node.value, (str, bytes)):
            return self._critical_name_in_text(node.value, self._CRITICAL_BUILTIN_NAME)
        return None

    def _reshaped_references(self, nodes: List[ast.AST], reshapes: List[ast.AST]) -> List[tuple[str, int]]:
        """(name, line) for each step on a string that can leave a critical
        name: a slice or index, a %-format, a str method that removes
        characters or changes case, str() or a concatenation (_string_step).

        Steps are worked out deepest first from the literals they start
        from, so a chain is worked out as a whole (``"xexecx"[1:][:-1]``,
        ``"xexec".upper().lower()[1:]``), and each result is matched as whole
        identifiers: ``"executing %s" % job`` and ``"executed,ok".split(",")``
        are not matches. A step that removes characters but cannot be worked
        out (arguments that are not literals, a method read without being
        called, a value too long to carry or one of unknown origin) matches
        anywhere the literals that can reach it (_ReachingLiterals), or the
        value an earlier step worked out.
        """
        called = {id(node.func) for node in reshapes if isinstance(node, ast.Call)}
        steps = _StringSteps(_ReachingLiterals(nodes))
        found: List[tuple[str, int]] = []
        # ast.walk is breadth first, so in reverse an operand comes before the step on it.
        for node in reversed(reshapes):
            name = None if id(node) in called else steps.check(node)
            if name:
                found.append((name, node.lineno))
        found.reverse()
        return found

    @classmethod
    def _string_step(cls, node: ast.AST) -> tuple[Optional[str], List[ast.AST]]:
        """How ``node`` reshapes a string, and the operands it works on:
        "remove" (a slice, a str method that can remove characters inside a
        word, or one read without being called), "format" (``%``), "keep"
        (an index, a case change, ``str()``, ``+``, or a method that cuts
        only between words: _keeps_words), or None."""
        if isinstance(node, ast.Subscript):
            # An index leaves one character, or one item whole.
            return ("remove" if isinstance(node.slice, ast.Slice) else "keep"), [node.value]
        if isinstance(node, ast.BinOp):
            return cls._operator_step(node)
        if isinstance(node, ast.Call) and cls._is_str_call(node):
            return "keep", [node.args[0]]
        method = node.func if isinstance(node, ast.Call) else node
        if not (isinstance(method, ast.Attribute) and method.attr in cls._LITERAL_RESHAPERS):
            return None, []
        if isinstance(node, ast.Attribute):
            return "remove", [method.value]
        receiver, _ = cls._method_call_parts(node)
        return ("keep" if cls._keeps_words(node) else "remove"), [receiver]

    @staticmethod
    def _operator_step(node: ast.BinOp) -> tuple[Optional[str], List[ast.AST]]:
        if isinstance(node.op, ast.Mod):
            return "format", [node.left, node.right]
        if isinstance(node.op, ast.Add):
            return "keep", [node.left, node.right]
        return None, []

    @staticmethod
    def _is_str_call(node: ast.Call) -> bool:
        return isinstance(node.func, ast.Name) and node.func.id == "str" and len(node.args) == 1 and not node.keywords

    @staticmethod
    def _method_call_parts(call: ast.Call) -> tuple[ast.AST, List[ast.AST]]:
        """The string a str method call works on and the arguments it
        passes: ``s.strip(c)``, or ``str.strip(s, c)`` through the class."""
        receiver = call.func.value
        if isinstance(receiver, ast.Name) and receiver.id == "str" and call.args:
            return call.args[0], call.args[1:]
        return receiver, call.args

    @classmethod
    def _keeps_words(cls, call: ast.Call) -> bool:
        """Whether a str method call leaves each word whole: a case change,
        or strip, split, partition and their variants cutting on whitespace
        or on a literal with no word characters. What those remove borders a
        word, so a name in what they leave was already a whole one."""
        method = call.func.attr
        if method in cls._CASE_METHODS:
            return True
        _, args = cls._method_call_parts(call)
        if method not in cls._EDGE_CUTTERS or any(isinstance(arg, ast.Starred) for arg in args):
            return False
        if any(keyword.arg is None for keyword in call.keywords):
            return False
        cut = args[0] if args else next((keyword.value for keyword in call.keywords if keyword.arg == "sep"), None)
        if cut is None or (isinstance(cut, ast.Constant) and cut.value is None):
            return True
        if not (isinstance(cut, ast.Constant) and isinstance(cut.value, (str, bytes))):
            return False
        return cls._WORD_CHARACTER.search(cls._literal_text(cut)) is None

    @classmethod
    def _step_result(cls, node: ast.AST, values: list):
        """What the step ``node`` leaves of its operands' ``values`` (str, or
        a list or tuple of str from split or partition), or None when that
        is not known. Raises when the arguments are not literals."""
        if isinstance(node, ast.Subscript):
            return values[0][cls._literal_index(node.slice)]
        if isinstance(node, ast.BinOp):
            return values[0] + values[1]
        if isinstance(node, ast.Attribute) or isinstance(node.func, ast.Name):
            # A method read without being called; or str() of a string.
            return None if isinstance(node, ast.Attribute) else values[0]
        method = node.func.attr
        _, arguments = cls._method_call_parts(node)
        args = [cls._literal_text(arg) for arg in arguments]
        kwargs = {keyword.arg: cls._literal_text(keyword.value) for keyword in node.keywords}
        # translate can map one character to many, and replace grows the text
        # when the new part is longer: not worked out, to bound the work.
        if method == "translate" or (method == "replace" and len(args) >= 2 and len(args[1]) > len(args[0])):
            return None
        return cls._LITERAL_RESHAPERS[method](values[0], *args, **kwargs)

    @staticmethod
    def _literal_index(node: ast.AST):
        """A slice or index written as int literals (``[1:]``, ``[-4:]``)."""
        if isinstance(node, ast.Slice):
            bounds = [None if bound is None else ast.literal_eval(bound) for bound in (node.lower, node.upper, node.step)]
            if any(bound is not None and type(bound) is not int for bound in bounds):
                raise TypeError("not an int slice")
            return slice(*bounds)
        index = ast.literal_eval(node)
        if type(index) is not int:
            raise TypeError("not an int index")
        return index

    @staticmethod
    def _literal_text(node: ast.AST):
        value = ast.literal_eval(node)
        return value.decode("latin-1") if isinstance(value, bytes) else value

    @classmethod
    def _critical_name_in_value(cls, value, pattern=None) -> Optional[str]:
        """A critical name a worked-out value (str, or list or tuple of str)
        holds as a whole identifier, or as ``pattern`` matches it."""
        pattern = pattern or cls._CRITICAL_BUILTIN_NAME
        parts = value if isinstance(value, (list, tuple)) else [value]
        return next(filter(None, (cls._critical_name_in_text(part, pattern)
                                  for part in parts if isinstance(part, str))), None)

    @staticmethod
    def _critical_name_in_text(value, pattern) -> Optional[str]:
        text = value.decode("latin-1") if isinstance(value, bytes) else value
        match = pattern.search(text)
        return match.group(1) if match else None

    @classmethod
    def _import_reference(cls, node: ast.AST) -> Optional[str]:
        """The critical name a from-import reads from any module, else the
        builtins module when the import is of it."""
        if isinstance(node, ast.Import):
            return next(
                (alias.name for alias in node.names if alias.name.split(".")[0] in cls.PYTHON_BUILTIN_MODULES),
                None,
            )
        critical = next((alias.name for alias in node.names if alias.name in cls._ATTRIBUTE_READ_NAMES), None)
        if critical or node.level or node.module not in cls.PYTHON_BUILTIN_MODULES:
            return critical
        return node.module

    @classmethod
    def _untrusted_compiles(cls, nodes: List[ast.AST], compile_attributes: List[ast.Attribute]) -> List[ast.Attribute]:
        """The ``name.compile`` reads that are not a regex compile: one is
        trusted only when called as ``re.compile(pattern, flags)`` on a name
        _imported_re_names trusts."""
        safe_re = cls._imported_re_names(nodes)
        if not safe_re:
            return compile_attributes
        regex_calls = {
            id(node.func) for node in nodes
            if isinstance(node, ast.Call) and cls._has_regex_compile_arguments(node)
        }
        return [node for node in compile_attributes if node.value.id not in safe_re or id(node) not in regex_calls]

    @classmethod
    def _has_regex_compile_arguments(cls, call: ast.Call) -> bool:
        """At most two arguments, none unpacked, keywords only pattern and flags."""
        return (
            len(call.args) + len(call.keywords) <= 2
            and not any(isinstance(arg, ast.Starred) for arg in call.args)
            and all(keyword.arg in cls._REGEX_COMPILE_KEYWORDS for keyword in call.keywords)
        )

    @classmethod
    def _imported_re_names(cls, nodes: List[ast.AST]) -> set:
        """Names every import binds to the ``re`` module and nothing rebinds.

        Empty when the code can rebind a name without an assignment the AST
        shows: through a namespace dict (``globals()["re"] = ...``,
        ``globals().update(re=...)``, a frame's ``f_globals``), the import
        system (``sys.modules.update(re=...)`` before ``import re``) or a star
        import.
        """
        bindings: Dict[str, set] = {}
        rebound = set()
        for node in nodes:
            if cls._writes_namespace(node):
                return set()
            for bound, module in cls._import_targets(node):
                bindings.setdefault(bound, set()).add(module)
            rebound.update(cls._names_rebound_by(node))
        return {name for name, modules in bindings.items() if modules == {"re"} and name not in rebound}

    @classmethod
    def _import_targets(cls, node: ast.AST) -> List[tuple[str, str]]:
        """(name bound, module bound to) for each name an import binds; a
        from-import never binds a module the re check trusts."""
        if isinstance(node, ast.Import):
            return [cls._import_binding(alias) for alias in node.names]
        if isinstance(node, ast.ImportFrom):
            return [(alias.asname or alias.name, "from-import") for alias in node.names]
        return []

    @classmethod
    def _writes_namespace(cls, node: ast.AST) -> bool:
        if isinstance(node, ast.ImportFrom):
            return any(alias.name == "*" or alias.name in cls._NAMESPACE_ACCESS for alias in node.names)
        if isinstance(node, ast.Name):
            return node.id in cls._NAMESPACE_ACCESS
        return isinstance(node, ast.Attribute) and node.attr in cls._NAMESPACE_ACCESS

    @staticmethod
    def _names_rebound_by(node: ast.AST) -> set:
        """Names ``node`` binds other than by an import: assignment targets,
        parameters, def and class names, ``except ... as``, match-pattern
        captures, and for an attribute set or deleted, both the attribute's
        name (``module.re = ...`` may be this module) and the object's
        (``re.compile = ...``)."""
        if isinstance(node, ast.Name):
            return set() if isinstance(node.ctx, ast.Load) else {node.id}
        if isinstance(node, ast.Attribute):
            if isinstance(node.ctx, ast.Load):
                return set()
            return {node.attr, node.value.id} if isinstance(node.value, ast.Name) else {node.attr}
        if isinstance(node, ast.arg):
            return {node.arg}
        if isinstance(node, ast.alias):
            return set()
        return {value for value in (getattr(node, "name", None), getattr(node, "rest", None)) if isinstance(value, str)}

    def _critical_builtin_issue(self, name: str, line_number: Optional[int]) -> SecurityIssue:
        if name in self.PYTHON_ATTRIBUTE_ACCESSORS:
            return SecurityIssue(
                severity="CRITICAL",
                issue_type="dangerous_attribute",
                pattern=name,
                description=f"Dangerous attribute access: {name}",
                line_number=line_number,
            )
        return SecurityIssue(
            severity="CRITICAL",
            issue_type="dangerous_function",
            pattern=name,
            description=self.PYTHON_CRITICAL.get(
                name, self.PYTHON_CODE_EXECUTION_NAMES.get(name, "Access to the builtins module")
            ),
            line_number=line_number,
            recommendation="Remove or sandbox this operation",
        )

    def _check_python_process_ast(self, nodes: List[ast.AST]) -> List[SecurityIssue]:
        """Flag process-execution and file/network calls, resolving import aliases.

        Catches what the line scan cannot: ``import subprocess as sp;
        sp.run(...)``, ``from os import system as run_it; run_it(...)``, bare
        calls to names brought in by ``from os import *``, calls on the raw-OS
        backend modules ``posix``/``nt``, the builtin ``open``, and file/network
        sinks reached through an alias (GHSA-4phf).
        """
        aliases, star_modules = self._import_aliases(nodes)
        issues: List[SecurityIssue] = []
        for node in nodes:
            name = self._dotted_name(node.func) if isinstance(node, ast.Call) else None
            if not name:
                continue
            issue = self._process_call_issue(
                name, self._call_candidates(name, aliases, star_modules), aliases, getattr(node, "lineno", None)
            )
            if issue:
                issues.append(issue)
        return issues

    @staticmethod
    def _call_candidates(name: str, aliases: Dict[str, str], star_modules: List[str]) -> List[str]:
        """The dotted names a call to ``name`` may resolve to."""
        head, _, rest = name.partition(".")
        if head in aliases:
            return [aliases[head] + ("." + rest if rest else "")]
        if not rest:
            return [name] + [f"{module}.{name}" for module in star_modules]
        return [name]

    def _process_call_issue(
        self, name: str, candidates: List[str], aliases: Dict[str, str], lineno: Optional[int]
    ) -> Optional[SecurityIssue]:
        """The process-execution or file/network finding for one call, if any."""
        # Process execution, incl. the raw-OS backend modules posix/nt
        # (matched by module head, so "nt." doesn't collide with words).
        hit = next((c for c in candidates if self._is_process_execution(c)), None)
        if hit is None:
            hit = next(
                (c for c in candidates
                 if "." in c and c.partition(".")[0] in self.PYTHON_RAW_OS_MODULES),
                None,
            )
        if hit:
            return self._process_execution_issue(hit, lineno)

        # Builtin open(): a bare call with no module, not shadowed by an
        # import that re-points the name elsewhere.
        if name in self.PYTHON_FILE_BUILTINS and name not in aliases:
            return self._file_network_issue(name, lineno)

        # File system / network sinks.
        fn_hit = next((c for c in candidates if self._is_file_network(c)), None)
        return self._file_network_issue(fn_hit, lineno) if fn_hit else None

    def _check_python_subprocess_ast(self, nodes: List[ast.AST]) -> List[SecurityIssue]:
        """Detect subprocess curl/wget pipe-to-shell patterns using AST."""
        issues: List[SecurityIssue] = []
        for node in nodes:
            if not isinstance(node, ast.Call):
                continue

            if not self._is_subprocess_call(node):
                continue

            issue = self._build_subprocess_pipe_issue(node)
            if issue:
                issues.append(issue)
        return issues

    def _build_subprocess_pipe_issue(self, node: ast.Call) -> SecurityIssue | None:
        """Build a subprocess pipe-to-shell issue when the command payload is dangerous."""
        command_text = self._extract_subprocess_command_text(node)
        if not self._is_pipe_to_shell_payload(command_text):
            return None

        shell_true = self._call_has_shell_true(node)
        return SecurityIssue(
            severity="CRITICAL",
            issue_type="remote_code_execution",
            pattern="subprocess + curl|wget pipe to shell",
            description=(
                "Remote code execution via shell=True with curl/wget pipe to shell."
                if shell_true
                else "Suspicious curl/wget pipe-to-shell pattern detected (heuristic)."
            ),
            line_number=getattr(node, "lineno", None),
            recommendation=(
                "Never execute remote pipe commands with shell=True."
                if shell_true
                else "Never pipe remote content directly into a shell."
            ),
        )

    def _is_pipe_to_shell_payload(self, command_text: str) -> bool:
        """Check whether command text resembles curl/wget pipe-to-shell execution."""
        if not command_text:
            return False

        command_lower = command_text.lower()
        has_downloader = "curl" in command_lower or "wget" in command_lower
        has_shell_target = self._SHELL_TARGET.search(command_lower) is not None
        has_chain_op = "|" in command_text or ";" in command_text or "&&" in command_text
        return has_downloader and has_shell_target and has_chain_op

    def _is_subprocess_call(self, node: ast.Call) -> bool:
        """Return True when call is subprocess.run/call/Popen/check_output."""
        if not isinstance(node.func, ast.Attribute):
            return False
        if not isinstance(node.func.value, ast.Name):
            return False
        return (
            node.func.value.id == "subprocess"
            and node.func.attr in {"run", "call", "Popen", "check_output"}
        )

    def _call_has_shell_true(self, node: ast.Call) -> bool:
        """Check whether subprocess call has shell=True."""
        for kw in node.keywords:
            if kw.arg == "shell" and isinstance(kw.value, ast.Constant) and kw.value.value is True:
                return True
        return False

    def _extract_subprocess_command_text(self, node: ast.Call) -> str:
        """Best-effort extraction of command text from subprocess call first arg."""
        if not node.args:
            return ""
        return self._expr_to_text(node.args[0])

    def _expr_to_text(self, expr: ast.AST) -> str:
        """Render AST expression to text for heuristic keyword matching."""
        if isinstance(expr, ast.Constant):
            return str(expr.value)

        if isinstance(expr, ast.JoinedStr):
            parts: List[str] = []
            for value in expr.values:
                if isinstance(value, ast.Constant):
                    parts.append(str(value.value))
                else:
                    parts.append("{expr}")
            return "".join(parts)

        if isinstance(expr, (ast.List, ast.Tuple)):
            return " ".join(self._expr_to_text(item) for item in expr.elts)

        try:
            return ast.unparse(expr)
        except (AttributeError, TypeError, ValueError, RecursionError):
            return ""
    
    def verify_python_deep(self, code: str) -> DiagnosticResult:
        """
        Deep Python verification combining pattern matching with AST taint analysis.
        
        This method performs two types of analysis:
        1. Pattern-based detection (fast, catches known dangerous patterns)
        2. Taint analysis (AST-based, tracks data flow from sources to sinks)
        
        Returns a :class:`DiagnosticResult`. The combined verdict is VERIFIED
        with ``is_valid`` True only when both the pattern scan and the taint
        analysis find no unsafe findings; otherwise it is VERIFIED as-unsafe
        (``is_valid`` False). Internal failures are BLOCKED
        (``code_verifier.execution_error``).
        
        Args:
            code: Python source code to analyze.
            
        Example:
            >>> result = verifier.verify_python_deep("x = input(); eval(x)")
            >>> print(result.developer_fields.get("taint_vulnerabilities"))
        """
        # Standard pattern-based check
        pattern_result = self.verify_code(code, "python")

        # If the pattern analysis was blocked (unsupported language, internal
        # error), propagate that fail-closed result instead of misrepresenting
        # it as a VERIFIED verdict (which would bind proof to no analysis).
        if pattern_result.is_fail_closed:
            return pattern_result

        # AST-based taint analysis — an exception must block, not escape.
        try:
            taint_result = self.taint_analyzer.analyze(code)
        except Exception:  # noqa: BLE001 — fail-closed by design
            return DiagnosticResult.blocked(
                agent_message="Deep code verification failed: taint analysis unavailable.",
                developer_fields={
                    "constraint_id": CONSTRAINT_EXECUTION_ERROR,
                    "is_valid": False,
                    "is_safe": False,
                    "reason": "taint analysis failed",
                },
            )

        is_safe = (
            pattern_result.developer_fields.get("is_valid") is True
            and taint_result["is_safe"]
        )

        developer_fields: Dict[str, Any] = {
            "constraint_id": CONSTRAINT_CODE_SAFE if is_safe else CONSTRAINT_CODE_UNSAFE,
            "is_safe": is_safe,
            "is_valid": is_safe,
            "language": "python",
            "analysis_methods": ["pattern_matching", "taint_analysis"],
            # Pattern-based results
            "pattern_issues": pattern_result.developer_fields.get("issues", []),
            "pattern_critical": pattern_result.developer_fields.get("critical_count", 0),
            "pattern_warnings": pattern_result.developer_fields.get("warning_count", 0),
            # Taint analysis results
            "taint_vulnerabilities": taint_result["vulnerabilities"],
            "tainted_variables": sorted(taint_result["tainted_variables"]),
            "data_flow_sources": taint_result["sources_found"],
            "data_flow_sinks": taint_result["sinks_found"],
            # Summary
            "summary": {
                "pattern_issues_found": len(pattern_result.developer_fields.get("issues", [])),
                "taint_vulnerabilities_found": len(taint_result["vulnerabilities"]),
                "tainted_variable_count": len(taint_result["tainted_variables"]),
                "is_safe": is_safe,
            },
        }

        evidence = {
            "engine": "CodeVerifier-Deep-Scanner",
            "language": "python",
            "analysis_methods": ["pattern_matching", "taint_analysis"],
            "is_safe": is_safe,
            "pattern_is_safe": pattern_result.developer_fields.get("is_valid") is True,
            "taint_is_safe": taint_result["is_safe"],
            "pattern_issue_types": sorted(
                {
                    issue["type"]
                    for issue in pattern_result.developer_fields.get("issues", [])
                }
            ),
            "taint_vulnerabilities": [
                {
                    "severity": v.get("severity"),
                    "description": v.get("description"),
                    "source": v.get("source"),
                }
                for v in taint_result["vulnerabilities"]
            ],
        }

        if is_safe:
            agent_message = "The code passed deep security verification and is safe to use."
        else:
            agent_message = "The code failed deep security verification and is not safe to use."

        return DiagnosticResult.verified(
            agent_message=agent_message,
            developer_fields=developer_fields,
            evidence=evidence,
        )
    
