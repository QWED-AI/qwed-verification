    def verify_code(self, code: str, language: str = "python") -> DiagnosticResult:
        """
        Verify code for security vulnerabilities.

        Returns a structured :class:`DiagnosticResult`:

        - Unsafe code (ANALYSIS flags a critical issue) → VERIFIED as-unsafe
          (``developer_fields.is_valid`` False, proof_ref bound to the analysis
          evidence). Proving a snippet is unsafe IS a successful proof, mirroring
          the SQL verifier's malicious classification (issue #253), so it is not
          BLOCKED.
        - Safe code → VERIFIED with ``is_valid`` True and proof_ref from the
          analysis evidence.
        - Unsupported language → BLOCKED (``code_verifier.unsupported_language``)
        - Internal error   → BLOCKED (``code_verifier.execution_error``)

        ``agent_message`` is agent-safe: it never leaks detection rules, rule
        IDs, or raw AST/regex output. Rule-level detail lives in
        ``developer_fields``.

        Args:
            code: The code snippet to verify.
            language: Programming language (default: "python").

        Example:
            >>> result = verifier.verify_code("eval('rm -rf /')", language="python")
            >>> print(result.developer_fields.get("is_safe"))
            False
        """
        # Normalize before the error boundary: a non-string language must
        # produce the documented BLOCKED result, not an AttributeError, so a
        # single malformed batch item cannot abort the whole batch.
        if not isinstance(language, str):
            return DiagnosticResult.blocked(
                agent_message=(
                    "Code verification could not be completed because the "
                    "specified language is not supported."
                ),
                developer_fields={
                    "constraint_id": CONSTRAINT_UNSUPPORTED_LANGUAGE,
                    "is_safe": False,
                    "is_valid": False,
                    "language": str(language),
                    "supported_languages": list(self.supported_languages),
                },
            )

        language = language.lower()

        # Map typescript to javascript
        if language == "typescript" or language == "ts":
            language = "javascript"
        if language == "js":
            language = "javascript"
        if language == "py":
            language = "python"

        if language not in self.supported_languages:
            return DiagnosticResult.blocked(
                agent_message=(
                    "Code verification could not be completed because the "
                    "specified language is not supported."
                ),
                developer_fields={
                    "constraint_id": CONSTRAINT_UNSUPPORTED_LANGUAGE,
                    "is_safe": False,
                    "is_valid": False,
                    "language": language,
                    "supported_languages": list(self.supported_languages),
                },
            )

        issues: List[SecurityIssue] = []
        try:
            # Language-specific checks
            if language == "python":
                issues.extend(self._check_python(code))
            elif language == "javascript":
                issues.extend(self._check_javascript(code))
            elif language == "java":
                issues.extend(self._check_java(code))
            elif language == "go":
                issues.extend(self._check_go(code))
            elif language == "sql":
                issues.extend(self._check_sql(code))

            # Cross-language secret detection
            issues.extend(self._check_secrets(code))
        except Exception as exc:  # noqa: BLE001 — fail-closed by design
            return DiagnosticResult.blocked(
                agent_message=(
                    "Code verification could not be completed due to an internal error."
                ),
                developer_fields={
                    "constraint_id": CONSTRAINT_EXECUTION_ERROR,
                    "is_safe": False,
                    "is_valid": False,
                    "error_type": type(exc).__name__,
                    "language": language,
                },
            )

        # Calculate counts
        critical_count = sum(1 for i in issues if i.severity == "CRITICAL")
        warning_count = sum(1 for i in issues if i.severity == "WARNING")
        info_count = sum(1 for i in issues if i.severity == "INFO")

        is_safe = critical_count == 0
        is_valid = is_safe
        constraint_id = CONSTRAINT_CODE_SAFE if is_safe else CONSTRAINT_CODE_UNSAFE

        developer_fields: Dict[str, Any] = {
            "constraint_id": constraint_id,
            "is_safe": is_safe,
            "is_valid": is_valid,
            "language": language,
            "issues": [
                {
                    "severity": i.severity,
                    "type": i.issue_type,
                    "pattern": i.pattern,
                    "description": i.description,
                    "line_number": i.line_number,
                    "recommendation": i.recommendation,
                }
                for i in issues
            ],
            "critical_count": critical_count,
            "warning_count": warning_count,
            "info_count": info_count,
            "engine": "CodeVerifier-Pattern-Scanner",
        }

        evidence = self._build_evidence(code, language, is_safe, issues)

        if is_safe:
            agent_message = "The code passed security verification and is safe to use."
        else:
            agent_message = "The code failed security verification and is not safe to use."

        return DiagnosticResult.verified(
            agent_message=agent_message,
            developer_fields=developer_fields,
            evidence=evidence,
        )

    def _build_evidence(
        self,
        code: str,
        language: str,
        is_safe: bool,
        issues: List[SecurityIssue],
    ) -> Dict[str, Any]:
        """Build deterministic, JSON-serializable proof evidence bound to the verdict."""
        return {
            "engine": "CodeVerifier-Pattern-Scanner",
            "language": language,
            "code": code,
            "is_safe": is_safe,
            "critical_count": sum(1 for i in issues if i.severity == "CRITICAL"),
            "warning_count": sum(1 for i in issues if i.severity == "WARNING"),
            "issue_types": sorted({i.issue_type for i in issues}),
        }
    
    # =========================================================================
    # Python Checks
    # =========================================================================
    
    @staticmethod
    def _positions(haystack: str, needles: tuple) -> List[int]:
        """Sorted start indices of any needle in haystack (one pass per needle)."""
        found: List[int] = []
        for needle in needles:
            start = 0
            while True:
                i = haystack.find(needle, start)
                if i == -1:
                    break
                found.append(i)
                start = i + 1
        found.sort()
        return found

    def _check_remote_pipe_to_shell(self, code: str) -> List[SecurityIssue]:
        """Flag `subprocess.*` calls that pipe curl/wget output into a shell.

        Replaces the old chained-`.*?` regex. The token positions are collected
        once, up front; each subprocess match then uses a binary search to check
        that a fetch tool, a shell separator and a shell appear after it, in
        order. Overall O(n + matches·log n) — no rescan per match, no
        backtracking. One finding per line.
        """
        issues: List[SecurityIssue] = []
        # All positions are computed against `code` (case-insensitive regexes),
        # so offsets never drift the way `code.lower()` can for characters whose
        # lowercase form changes length (Sentry on PR #447).
        fetch_pos = [m.start() for m in self._FETCH_TOOL.finditer(code)]
        if not fetch_pos:
            return issues
        sep_pos = self._positions(code, ("|", ";", "&&"))
        if not sep_pos:
            return issues
        shell_pos = [m.start() for m in self._SHELL_TARGET.finditer(code)]
        if not shell_pos:
            return issues
        # Everything else is precomputed too, so each match is O(log n) and the
        # worst case (many matches on one line) stays near-linear overall.
        newline_pos = self._positions(code, ("\n",))
        shell_true_pos = [m.start() for m in self._SHELL_TRUE.finditer(code)]
        seen_lines = set()
        for match in self._SUBPROC_CALL.finditer(code):
            fi = bisect_left(fetch_pos, match.end())
            if fi == len(fetch_pos):
                continue
            si = bisect_left(sep_pos, fetch_pos[fi])
            if si == len(sep_pos):
                continue
            hi = bisect_left(shell_pos, sep_pos[si])
            if hi == len(shell_pos):
                continue
            line_num = bisect_left(newline_pos, match.start()) + 1
            if line_num in seen_lines:
                continue
            seen_lines.add(line_num)
            ti = bisect_left(shell_true_pos, match.start())
            if ti != len(shell_true_pos):
                description = "Remote code execution via shell=True with curl/wget pipe to shell."
                recommendation = "Never execute remote pipe commands with shell=True."
            else:
                description = "Suspicious curl/wget pipe-to-shell pattern detected (heuristic)."
                recommendation = "Never pipe remote content directly into a shell."
            issues.append(SecurityIssue(
                severity="CRITICAL",
                issue_type="remote_code_execution",
                pattern="subprocess + curl|wget pipe to shell",
                description=description,
                line_number=line_num,
                recommendation=recommendation,
            ))
        return issues

    def _check_python(self, code: str) -> List[SecurityIssue]:
        """Check Python code for security issues."""
        issues = []
        lines = code.split('\n')
        
        for line_num, line in enumerate(lines, 1):
            # Critical functions; the builtins among them are matched as
            # names in _check_python_critical_builtins (#534).
            for pattern, desc in self.PYTHON_CRITICAL.items():
                if pattern not in self.PYTHON_CRITICAL_BUILTINS and pattern in line:
                    issues.append(SecurityIssue(
                        severity="CRITICAL",
                        issue_type="dangerous_function",
                        pattern=pattern,
                        description=desc,
                        line_number=line_num,
                        recommendation="Remove or sandbox this operation"
                    ))
            
            # Shell and process execution: one blocking finding per line.
            for prefix in self.PYTHON_PROCESS_EXECUTION:
                if prefix in line:
                    issues.append(self._process_execution_issue(prefix.rstrip("._"), line_num))
                    break

            # File / network access: one blocking finding per line (GHSA-4phf).
            for prefix in self.PYTHON_FILE_NETWORK:
                if prefix in line:
                    issues.append(self._file_network_issue(prefix.rstrip("."), line_num))
                    break

            # Warning functions
            for pattern, desc in self.PYTHON_WARNING.items():
                if pattern in line:
                    issues.append(SecurityIssue(
                        severity="WARNING",
                        issue_type="context_dependent",
                        pattern=pattern,
                        description=desc,
                        line_number=line_num,
                        recommendation="Verify input source is trusted"
                    ))
            
            # Dangerous attributes
            for attr in self.PYTHON_DANGEROUS_ATTRS:
                if attr in line:
                    issues.append(SecurityIssue(
                        severity="CRITICAL",
                        issue_type="dangerous_attribute",
                        pattern=attr,
                        description=f"Dangerous attribute access: {attr}",
                        line_number=line_num
                    ))

        # The AST checks share one parse.
        tree = self._parse_python(code)
        issues.extend(self._check_python_critical_builtins(code, tree))

        # A subprocess call that pipes curl/wget output into a shell, including
        # across lines. Linear scan (no backtracking regex) over the full code.
        for issue in self._check_remote_pipe_to_shell(code):
            if any(
                i.issue_type == issue.issue_type and i.line_number == issue.line_number
                for i in issues
            ):
                continue
            issues.append(issue)

        # Process execution reached through an alias, which the line scan cannot see.
        for issue in self._check_python_process_ast(tree):
            if any(
                i.issue_type == issue.issue_type
                and i.line_number == issue.line_number
                for i in issues
            ):
                continue
            issues.append(issue)

        # AST-based subprocess checks to catch nested expression forms that regex can miss.
        for issue in self._check_python_subprocess_ast(tree):
            if any(
                i.issue_type == issue.issue_type
                and i.line_number == issue.line_number
                for i in issues
            ):
                continue
            issues.append(issue)
        
        # Weak crypto in password context
        code_lower = code.lower()
        has_password = any(p in code_lower for p in self.PASSWORD_INDICATORS)
        if has_password:
            for pattern, desc in self.PYTHON_WEAK_CRYPTO.items():
                if pattern in code:
                    issues.append(SecurityIssue(
                        severity="CRITICAL",
                        issue_type="weak_crypto_with_password",
                        pattern=pattern,
                        description=f"{desc} - used in password context",
                        recommendation="Use bcrypt, argon2, or scrypt for passwords"
                    ))
        
        return issues

    @staticmethod
    def _parse_python(code: str) -> Optional[ast.AST]:
        """The module's AST, or None for code that does not parse."""
        try:
            return ast.parse(code)
        except SyntaxError:
            return None

