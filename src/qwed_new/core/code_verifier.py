    # Batch Verification
    # =========================================================================
    
    def verify_batch(self, snippets: List[Dict[str, str]]) -> DiagnosticResult:
        """
        Verify multiple code snippets.

        Returns a single :class:`DiagnosticResult`. Per-snippet verdicts live in
        ``developer_fields.results`` (each a serialized per-snippet
        DiagnosticResult) and ``developer_fields.summary``.

        The batch is authoritative (VERIFIED with ``proof_ref``) only when every
        snippet is safe. A batch containing any unsafe snippet returns a VERIFIED
        as-unsafe batch (``is_valid`` False) so generic consumers that admit on
        ``is_authoritative`` can never accept unsafe code.

        Args:
            snippets: List of dicts with {"code": str, "language": str}.

        Example:
            >>> batch = [{"code": "print(1)", "language": "python"}, {"code": "alert(1)", "language": "js"}]
            >>> result = verifier.verify_batch(batch)
        """
        items: List[Dict[str, Any]] = []

        for snippet in snippets:
            result = self.verify_code(
                snippet.get("code", ""),
                snippet.get("language", "python")
            )
            serialized = result.to_dict()
            serialized["language"] = snippet.get("language", "python")
            items.append(serialized)

        total = len(snippets)

        # Fail closed: an empty batch proves nothing and must not be admitted.
        if total == 0:
            return DiagnosticResult.blocked(
                agent_message="Batch code verification failed: no snippets were provided.",
                developer_fields={
                    "constraint_id": CONSTRAINT_EMPTY_BATCH,
                    "is_valid": False,
                    "is_safe": False,
                    "summary": {"total": 0, "safe": 0, "blocked": 0},
                    "results": [],
                    "engine": "CodeVerifier-Pattern-Scanner",
                },
            )

        # Fail closed: any item that could not be completed (unsupported
        # language, internal error) is BLOCKED, not VERIFIED-as-unsafe.
        for item in items:
            if item["status"] != "VERIFIED":
                return DiagnosticResult.blocked(
                    agent_message=(
                        "Batch verification blocked: some snippets could not be "
                        "analyzed; the batch is not admissible."
                    ),
                    developer_fields={
                        "constraint_id": CONSTRAINT_BATCH_BLOCKED,
                        "is_valid": False,
                        "is_safe": False,
                        "blocked_item_status": item["status"],
                        "results": items,
                        "summary": {
                            "total": total,
                            "blocked": sum(1 for it in items if it["status"] != "VERIFIED"),
                        },
                        "engine": "CodeVerifier-Pattern-Scanner",
                    },
                )

        safe = sum(1 for item in items if item["developer_fields"].get("is_valid") is True)
        blocked = total - safe
        is_safe_all = safe == total

        summary = {
            "total": total,
            "safe": safe,
            "unsafe": blocked,
            "blocked": blocked,
            "total_critical": sum(item["developer_fields"].get("critical_count", 0) for item in items),
            "total_warnings": sum(item["developer_fields"].get("warning_count", 0) for item in items),
        }

        batch_fields: Dict[str, Any] = {
            "constraint_id": CONSTRAINT_CODE_SAFE if is_safe_all else CONSTRAINT_CODE_UNSAFE,
            "is_safe": is_safe_all,
            "is_valid": is_safe_all,
            "results": items,
            "summary": summary,
            "engine": "CodeVerifier-Pattern-Scanner",
        }

        # Batch proof must bind the complete inputs. Retain a digest of each
        # full snippet (proof-bearing) alongside truncated display text.
        snippet_digests: List[str] = []
        display_snippets: List[str] = []
        for snippet in snippets:
            raw = snippet.get("code", "")
            display_snippets.append(raw[:100] + "..." if len(raw) > 100 else raw)
            snippet_digests.append(hashlib.sha256(raw.encode("utf-8")).hexdigest())

        evidence = {
            "engine": "CodeVerifier-Pattern-Scanner",
            "count": total,
            "snippets": display_snippets,
            "snippet_digests": snippet_digests,
            "is_safe": is_safe_all,
            "verdicts": [
                {"status": item["status"], "is_valid": item["developer_fields"].get("is_valid")}
                for item in items
            ],
        }

        if is_safe_all:
            agent_message = "Batch code verification succeeded: all snippets passed security checks."
        else:
            agent_message = "Batch code verification flagged unsafe snippets; the batch is not admissible."

        return DiagnosticResult.verified(
            agent_message=agent_message,
            developer_fields=batch_fields,
            evidence=evidence,
        )

